from dataclasses import dataclass
from typing import Any, Callable, Optional
from analytics.services.metrics.result import MetricResult, MetricUnit


@dataclass
class MetricDefinition:
    """Metadata specification for a registered financial metric."""

    metric_id: str
    name: str
    category: str  # profitability, capital_allocation, investment_appraisal, liquidity, leverage, efficiency, break_even
    formula_description: str
    unit: MetricUnit
    formula_version: str = "v1"
    is_ledger_derived: bool = True
    interpretation: str = ""
    limitations: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "metric_id": self.metric_id,
            "name": self.name,
            "category": self.category,
            "formula_description": self.formula_description,
            "unit": self.unit.value if hasattr(self.unit, "value") else str(self.unit),
            "formula_version": self.formula_version,
            "is_ledger_derived": self.is_ledger_derived,
            "interpretation": self.interpretation,
            "limitations": self.limitations,
        }


class FinancialMetricRegistry:
    """Central registry cataloging all implemented financial metrics."""

    def __init__(self):
        self._metrics: dict[str, MetricDefinition] = {}
        self._register_defaults()

    def register(self, definition: MetricDefinition) -> None:
        self._metrics[definition.metric_id] = definition

    def get(self, metric_id: str) -> Optional[MetricDefinition]:
        return self._metrics.get(metric_id)

    def list_all(self, category: Optional[str] = None) -> list[MetricDefinition]:
        metrics = list(self._metrics.values())
        if category:
            metrics = [m for m in metrics if m.category.lower() == category.lower()]
        return metrics

